"""Правила продажи билетов — единственное место, где задаются цены и границы.

Значения отдаются клиенту через `GET /api/event`, фронтенд своих констант не хранит.
"""

# Возраст, с которого нужен полный билет; младше — детский
FULL_TICKET_MIN_AGE = 14
# Участнику младше этого возраста нужен сопровождающий. Сейчас совпадает с границей детского
# билета; если «ребёнком» считать всех младше 18 лет, достаточно поменять на 18.
ESCORT_REQUIRED_BELOW_AGE = FULL_TICKET_MIN_AGE
# Возраст сопровождающего: ребёнка допускают только вместе с участником не младше этого возраста
ADULT_MIN_AGE = 18

# Размер группы в одном заказе
MIN_PARTICIPANTS = 1
MAX_PARTICIPANTS = 4

# Допустимые значения полей участника
MIN_AGE = 0
MAX_AGE = 120
MAX_NAME_LENGTH = 100

# Цены в целых рублях (без float, чтобы не копить ошибки округления)
FULL_PRICE = 2000
CHILD_PRICE = 1000


def requires_escort(age: int) -> bool:
    """Нужен ли участнику сопровождающий.

    Единственное место, где определено, кого считать «ребёнком» в правиле сопровождения.
    """
    return age < ESCORT_REQUIRED_BELOW_AGE
